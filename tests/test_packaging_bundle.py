def binary(system: str, architecture: str) -> bytes:
    if system == "linux":
        data = bytearray(64)
        data[:6] = b"\x7fELF\x02\x01"
        struct.pack_into("<HH", data, 16, 3, 62 if architecture == "x86_64" else 183)
    elif system == "macos":
        data = bytearray(32)
        data[:4] = b"\xcf\xfa\xed\xfe"
        struct.pack_into("<I", data, 4, 0x01000007 if architecture == "x86_64" else 0x0100000C)
        struct.pack_into("<I", data, 12, 6)
    else:
        data = bytearray(128)
        data[:2] = b"MZ"
        struct.pack_into("<I", data, 60, 64)
        data[64:68] = b"PE\0\0"
        struct.pack_into("<H", data, 68, 0x8664 if architecture == "x86_64" else 0xAA64)
    return bytes(data) + b"geometry_pyramid test fixture"


class BundleFixture(unittest.TestCase):
    def setUp(self) -> None:
        self.temporary = tempfile.TemporaryDirectory(prefix="gp packaging ")
        self.addCleanup(self.temporary.cleanup)
        self.path = Path(self.temporary.name)
        self.staging = self.path / "staging"
        self.output = self.path / "dist"

    def prepare(self, system: str = "linux", major: int = 17, architecture: str = "x86_64") -> tuple[argparse.Namespace, Path, dict[str, str]]:
        values = {
            "--version": f"PostgreSQL {major}.4",
            "--pkglibdir": f"/ci/build/postgresql-{major}/lib",
            "--sharedir": f"/ci/build/postgresql-{major}/share",
        }
        if system == "windows":
            libdir = self.staging / "lib"
            extdir = self.staging / "share" / "extension"
            suffix = ".dll"
        else:
            libdir = self.staging / values["--pkglibdir"].lstrip("/")
            extdir = self.staging / values["--sharedir"].lstrip("/") / "extension"
            suffix = ".dylib" if system == "macos" and major >= 16 else ".so"
        libdir.mkdir(parents=True, exist_ok=True)
        extdir.mkdir(parents=True, exist_ok=True)
        library = libdir / ("geometry_pyramid" + suffix)
        library.write_bytes(binary(system, architecture))
        (extdir / "geometry_pyramid.control").write_text("default_version = '0.1.1'\nrequires = 'postgis'\n", encoding="ascii")
        (extdir / "geometry_pyramid--0.1.1.sql").write_text("SELECT 1;\n", encoding="ascii")
        (extdir / "geometry_pyramid--0.1.0--0.1.1.sql").write_text("SELECT 2;\n", encoding="ascii")
        args = argparse.Namespace(
            staging=self.staging, pg_config="unused-pg-config",
            platform={"linux": "ubuntu-24.04", "macos": "macos-15", "windows": "windows-2022"}[system],
            arch=architecture, out_dir=self.output, commit="a" * 40,
        )
        return args, library, values

    def package(self, args: argparse.Namespace, values: dict[str, str]) -> Path:
        with patch.object(PACKAGE, "pg_value", side_effect=lambda _, option: values[option]), patch.object(PACKAGE, "source_identity", return_value=("a" * 40, 1700000000)):
            return PACKAGE.make_bundle(args)

    def extract(self, archive: Path) -> Path:
        extraction = self.path / "extracted"
        if archive.name.endswith(".zip"):
            with zipfile.ZipFile(archive) as source:
                source.extractall(extraction)
            return extraction / archive.name.removesuffix(".zip")
        with tarfile.open(archive) as source:
            # Archives are generated by the code under test in a private directory.
            source.extractall(extraction, filter="data")
        return extraction / archive.name.removesuffix(".tar.gz")

class BundleTests(BundleFixture):
    def test_archive_contains_verified_payload_without_builder_paths(self) -> None:
        args, _, values = self.prepare()
        archive = self.package(args, values)
        self.assertEqual(archive.name, "geometry_pyramid-v0.1.1-pg17-ubuntu-24.04-x86_64.tar.gz")
        digest, filename = archive.with_name(archive.name + ".sha256").read_text().split()
        self.assertEqual(filename, archive.name)
        self.assertEqual(digest, hashlib.sha256(archive.read_bytes()).hexdigest())
        bundle = self.extract(archive)
        manifest = json.loads((bundle / "manifest.json").read_text())
        self.assertEqual(manifest["postgresql"]["major"], 17)
        self.assertEqual(manifest["target"]["architecture"], "x86_64")
        self.assertNotIn("/ci/build", (bundle / "manifest.json").read_text())
        self.assertTrue((bundle / "extension" / "geometry_pyramid--0.1.0--0.1.1.sql").is_file())
        for line in (bundle / "SHA256SUMS").read_text().splitlines():
            expected, relative = line.split("  ", 1)
            self.assertEqual(expected, hashlib.sha256((bundle / relative).read_bytes()).hexdigest())
        first = archive.read_bytes()
        self.package(args, values)
        self.assertEqual(first, archive.read_bytes())

    def test_binary_architecture_and_os_must_match_the_label(self) -> None:
        args, library, values = self.prepare()
        args.arch = "aarch64"
        with self.assertRaisesRegex(ValueError, "binary is linux/x86_64"):
            self.package(args, values)
        args.arch = "x86_64"
        library.write_bytes(binary("macos", "x86_64"))
        with self.assertRaisesRegex(ValueError, "binary is macos/x86_64"):
            self.package(args, values)

    def test_macos_uses_the_postgresql_version_specific_library_suffix(self) -> None:
        for major, suffix in [(13, ".so"), (15, ".so"), (16, ".dylib"), (18, ".dylib")]:
            with self.subTest(major=major):
                args, _, values = self.prepare("macos", major, "aarch64")
                bundle = self.extract(self.package(args, values))
                self.assertTrue((bundle / "lib" / ("geometry_pyramid" + suffix)).is_file())
                self.assertTrue((bundle / "install.sh").is_file())

    def test_windows_zip_uses_pgrx_windows_staging_and_powershell(self) -> None:
        args, _, values = self.prepare("windows", 18)
        archive = self.package(args, values)
        self.assertEqual(archive.name, "geometry_pyramid-v0.1.1-pg18-windows-2022-x86_64.zip")
        bundle = self.extract(archive)
        self.assertTrue((bundle / "lib" / "geometry_pyramid.dll").is_file())
        self.assertTrue((bundle / "install.ps1").is_file())
        self.assertFalse((bundle / "install.sh").exists())

    def test_unresolved_control_version_is_rejected(self) -> None:
        args, _, values = self.prepare()
        control = next(self.staging.rglob("geometry_pyramid.control"))
        control.write_text("default_version = '@CARGO_VERSION@'\n", encoding="ascii")
        with self.assertRaisesRegex(ValueError, "resolved default_version"):
            self.package(args, values)

    @unittest.skipIf(os.name == "nt", "Windows symlink creation needs extra permissions")
    def test_symlink_artifacts_are_rejected(self) -> None:
        args, library, values = self.prepare()
        real = library.with_suffix(".real")
        library.rename(real)
        library.symlink_to(real.name)
        with self.assertRaisesRegex(ValueError, "regular artifact"):
            self.package(args, values)


@unittest.skipUnless(sys.platform in ("linux", "darwin") and platform.machine().lower() in ("x86_64", "aarch64", "arm64"), "native Linux/macOS installer tests")
class InstallerTests(BundleFixture):
    def installer_fixture(self, major: int = 17) -> tuple[Path, Path, Path, bytes]:
        system = "macos" if sys.platform == "darwin" else "linux"
        architecture = "aarch64" if platform.machine().lower() in ("aarch64", "arm64") else "x86_64"
        args, library, values = self.prepare(system, major, architecture)
        contents = library.read_bytes()
        bundle = self.extract(self.package(args, values))
        target = self.path / "customer PostgreSQL"
        (target / "bin").mkdir(parents=True)
        postgres = target / "bin" / "postgres"
        postgres.write_bytes(binary(system, architecture))
        postgres.chmod(0o755)
        pg_config = target / "bin" / "pg_config"
        self.write_pg_config(pg_config, target, major)
        return bundle, pg_config, target, contents

    @staticmethod
    def write_pg_config(pg_config: Path, target: Path, major: int) -> None:
        mapping = {
            "--version": f"PostgreSQL {major}.7", "--bindir": str(target / "bin"),
            "--pkglibdir": str(target / "lib"), "--sharedir": str(target / "share"),
        }
        pg_config.write_text(f"#!{sys.executable}\nimport sys\nprint({mapping!r}[sys.argv[1]])\n", encoding="utf-8")
        pg_config.chmod(0o755)

    @staticmethod
    def install(bundle: Path, pg_config: Path, *extra: str, environment=None) -> subprocess.CompletedProcess[str]:
        return subprocess.run(["bash", str(bundle / "install.sh"), "--pg-config", str(pg_config), *extra], text=True, capture_output=True, env=environment)

    def fail_moves(self, *counts: int) -> dict[str, str]:
        tools = self.path / "fault tools"
        tools.mkdir()
        count_file = self.path / "mv-count"
        real_mv = shutil.which("mv")
        self.assertIsNotNone(real_mv)
        wrapper = tools / "mv"
        wrapper.write_text(
            f"#!{sys.executable}\nimport os, pathlib, sys\n"
            f"counter=pathlib.Path({str(count_file)!r})\n"
            "count=int(counter.read_text())+1 if counter.exists() else 1\n"
            "counter.write_text(str(count))\n"
            f"if count in {counts!r}:\n    print('injected mv failure',file=sys.stderr)\n    sys.exit(1)\n"
            f"os.execv({real_mv!r},[{real_mv!r},*sys.argv[1:]])\n",
            encoding="utf-8",
        )
        wrapper.chmod(0o755)
        return dict(os.environ, PATH=str(tools) + os.pathsep + os.environ["PATH"])

    def test_relocates_and_replaces_without_modifying_the_old_inode(self) -> None:
        bundle, pg_config, target, contents = self.installer_fixture()
        library = next((bundle / "lib").iterdir())
        destination = target / "lib" / library.name
        destination.parent.mkdir()
        destination.write_bytes(b"previous loaded library")
        with destination.open("rb") as old_handle:
            previous_inode = destination.stat().st_ino
            result = self.install(bundle, pg_config)
            self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
            self.assertEqual(old_handle.read(), b"previous loaded library")
            self.assertNotEqual(previous_inode, destination.stat().st_ino)
        self.assertEqual(destination.read_bytes(), contents)
        self.assertTrue((target / "share" / "extension" / "geometry_pyramid.control").is_file())
        self.assertNotIn("/ci/build", result.stdout)

    def test_wrong_pg_major_is_rejected_before_writes(self) -> None:
        bundle, pg_config, target, _ = self.installer_fixture()
        self.write_pg_config(pg_config, target, 18)
        result = self.install(bundle, pg_config)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("requires PostgreSQL 17", result.stderr)
        self.assertFalse((target / "lib").exists())

    def test_failed_second_rename_restores_existing_library(self) -> None:
        bundle, pg_config, target, _ = self.installer_fixture()
        library = target / "lib" / next((bundle / "lib").iterdir()).name
        library.parent.mkdir()
        library.write_bytes(b"old library")
        extension_dir = target / "share" / "extension"
        extension_dir.mkdir(parents=True)
        control = extension_dir / "geometry_pyramid.control"
        control.write_bytes(b"old control")
        with library.open("rb") as old_handle:
            result = self.install(bundle, pg_config, environment=self.fail_moves(2))
            self.assertNotEqual(result.returncode, 0)
            self.assertEqual(old_handle.read(), b"old library")
        self.assertEqual(library.read_bytes(), b"old library")
        self.assertEqual(control.read_bytes(), b"old control")
        self.assertFalse(list(extension_dir.glob("*.sql")))
        self.assertFalse(list(target.rglob(".geometry_pyramid.*")))

    def test_failed_third_rename_removes_new_files(self) -> None:
        bundle, pg_config, target, _ = self.installer_fixture()
        result = self.install(bundle, pg_config, environment=self.fail_moves(3))
        self.assertNotEqual(result.returncode, 0)
        self.assertFalse(list((target / "lib").iterdir()))
        self.assertFalse(list((target / "share" / "extension").iterdir()))

    def test_failed_rollback_keeps_the_backup_and_reports_its_path(self) -> None:
        bundle, pg_config, target, contents = self.installer_fixture()
        library = target / "lib" / next((bundle / "lib").iterdir()).name
        library.parent.mkdir()
        library.write_bytes(b"recover this old library")
        result = self.install(bundle, pg_config, environment=self.fail_moves(2, 3))
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("Automatic rollback could not finish", result.stderr)
        backups = list(target.rglob(".geometry_pyramid.backup.*"))
        self.assertEqual(len(backups), 1)
        self.assertEqual(backups[0].read_bytes(), b"recover this old library")
        self.assertIn(str(backups[0]), result.stderr)
        self.assertEqual(library.read_bytes(), contents)

    def test_corrupt_payload_is_rejected_before_writes(self) -> None:
        bundle, pg_config, target, _ = self.installer_fixture()
        next((bundle / "lib").iterdir()).write_bytes(b"tampered")
        result = self.install(bundle, pg_config)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("checksum verification failed", result.stderr)
        self.assertFalse((target / "lib").exists())

    def test_unlisted_payload_is_rejected_before_writes(self) -> None:
        bundle, pg_config, target, _ = self.installer_fixture()
        checksums = bundle / "SHA256SUMS"
        checksums.write_text("\n".join(line for line in checksums.read_text().splitlines() if not line.endswith("package.metadata")) + "\n")
        result = self.install(bundle, pg_config)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("missing from SHA256SUMS: package.metadata", result.stderr)
        self.assertFalse((target / "lib").exists())

    def test_target_server_architecture_is_checked(self) -> None:
        bundle, pg_config, target, _ = self.installer_fixture()
        system = "macos" if sys.platform == "darwin" else "linux"
        wrong = "x86_64" if platform.machine().lower() in ("aarch64", "arm64") else "aarch64"
        (target / "bin" / "postgres").write_bytes(binary(system, wrong))
        result = self.install(bundle, pg_config)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("server architecture does not match", result.stderr)
        self.assertFalse((target / "lib").exists())

    def test_dry_run_has_no_installation_side_effects(self) -> None:
        bundle, pg_config, target, _ = self.installer_fixture()
        result = self.install(bundle, pg_config, "--dry-run")
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertFalse((target / "lib").exists())

    def test_destdir_stages_under_the_requested_root(self) -> None:
        bundle, pg_config, target, _ = self.installer_fixture()
        destination_root = self.path / "system-package"
        result = self.install(bundle, pg_config, "--destdir", str(destination_root))
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertFalse((target / "lib").exists())
        staged_target = destination_root / str(target).lstrip("/")
        self.assertTrue((staged_target / "share" / "extension" / "geometry_pyramid.control").is_file())


class PowerShellSyntaxTests(unittest.TestCase):
    @unittest.skipUnless(shutil.which("pwsh"), "PowerShell 7 is required for its native AST parser")
    def test_installer_parses_in_powershell(self) -> None:
        code = "$tokens=$null; $errors=$null; [System.Management.Automation.Language.Parser]::ParseFile($env:GP_INSTALLER_FILE,[ref]$tokens,[ref]$errors) | Out-Null; if ($errors.Count) { $errors | Out-String | Write-Error; exit 1 }"
        result = subprocess.run([shutil.which("pwsh"), "-NoProfile", "-Command", code], env=dict(os.environ, GP_INSTALLER_FILE=str(ROOT / "scripts" / "install.ps1")), text=True, capture_output=True)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)


